-- Files that belong to records, as blobs, and the links that say which record each file belongs to.
-- Idempotent: every start runs it. A replaced file is a new row whose REPLACES names the one it took over
-- from, so a link's current file heads a chain of earlier revisions; a removed link keeps its rows until
-- an administrator purges them. The table names are quoted capitals, as the setup screen and its grants name
-- them; the columns are unquoted and fold to lower case, as the store's queries write them. Needs PostgreSQL 10
-- or later for identity columns. Written from PostgreSQL's documentation and not yet run against a live server.
CREATE TABLE IF NOT EXISTS "APP_ATTACHMENT" (
    ATTACHMENT_ID bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_APP_ATTACHMENT PRIMARY KEY,
    FILE_NAME     varchar(260)  NOT NULL,
    CONTENT_TYPE  varchar(200)  NOT NULL,
    SIZE          bigint        NOT NULL,
    SHA256        char(64)      NOT NULL,
    CONTENT       bytea         NOT NULL,
    UPLOADED_BY   varchar(200)  NOT NULL,
    UPLOADED_AT   timestamptz   NOT NULL,
    REPLACES      bigint        NULL CONSTRAINT FK_APP_ATTACHMENT_REPLACES REFERENCES "APP_ATTACHMENT" (ATTACHMENT_ID)
);
CREATE TABLE IF NOT EXISTS "APP_ATTACHMENT_LINK" (
    LINK_ID       bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_APP_ATTACHMENT_LINK PRIMARY KEY,
    OWNER_ALIAS   varchar(200)  NOT NULL,
    OWNER_KEY     varchar(200)  NOT NULL,
    ATTACHMENT_ID bigint        NOT NULL CONSTRAINT FK_APP_ATTACHMENT_LINK_FILE REFERENCES "APP_ATTACHMENT" (ATTACHMENT_ID),
    PURPOSE       varchar(200)  NULL,
    LABEL         varchar(200)  NULL,
    NOTES         varchar(1000) NULL,
    CREATED_BY    varchar(200)  NOT NULL,
    CREATED_AT    timestamptz   NOT NULL,
    UPDATED_BY    varchar(200)  NOT NULL,
    UPDATED_AT    timestamptz   NOT NULL,
    REMOVED_BY    varchar(200)  NULL,
    REMOVED_AT    timestamptz   NULL
);
CREATE INDEX IF NOT EXISTS IX_APP_ATTACHMENT_LINK_OWNER ON "APP_ATTACHMENT_LINK" (OWNER_ALIAS, OWNER_KEY, REMOVED_AT);
CREATE INDEX IF NOT EXISTS IX_APP_ATTACHMENT_REPLACES ON "APP_ATTACHMENT" (REPLACES);
